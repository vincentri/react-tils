import data from './compare.json'
import { REPO } from './docs'

type Cell = {
  hook: string
  size: number
  server: 'ok' | 'throws' | 'warns'
  hydration: 'ok' | 'mismatch' | 'skipped'
  leaks: 'ok' | 'leaks'
  detail?: string
} | null
type Task = { id: string; task: string; notes: Record<string, string>; cells: Record<string, Cell> }
const tasks = data.tasks as Task[]
const libraries = data.libraries

const NAMES: Record<string, string> = {
  'react-tils': 'react-tils',
  uidotdev: '@uidotdev/usehooks',
  'usehooks-ts': 'usehooks-ts',
  mantine: '@mantine/hooks',
  'react-use': 'react-use',
  reactuses: '@reactuses/core',
  ahooks: 'ahooks',
}

const passes = (cell: Cell | undefined) =>
  !!cell && cell.server === 'ok' && cell.hydration === 'ok' && cell.leaks === 'ok'

function verdict(cell: NonNullable<Cell>): { mark: string; label: string; kind: string } {
  if (cell.server === 'throws') return { mark: '✕', label: 'Throws on the server', kind: 'bad' }
  if (cell.hydration === 'mismatch') return { mark: '!', label: 'Hydration mismatch', kind: 'warn' }
  if (cell.leaks === 'leaks') return { mark: '!', label: 'Leaks listeners', kind: 'warn' }
  if (cell.server === 'warns') return { mark: '!', label: 'Warns on the server', kind: 'warn' }
  return { mark: '✓', label: 'Passes', kind: 'good' }
}

const kb = (bytes: number) => `${(bytes / 1000).toFixed(1)} kB`

/** Per library: tasks it has a hook for, how many pass every check, and how many are the smallest. */
const summary = libraries.map(({ id }) => {
  const cells = tasks.map((t) => t.cells[id]).filter(Boolean)
  const smallest = tasks.filter((t) => {
    const own = t.cells[id]
    const sizes = Object.values(t.cells)
      .filter(Boolean)
      .map((c) => c!.size)
    return own && sizes.length > 1 && own.size === Math.min(...sizes)
  }).length
  return { id, has: cells.length, pass: cells.filter(passes).length, smallest }
})

export function Compare() {
  const ours = summary[0]!
  const others = summary.slice(1)
  const othersFailing = others.filter((s) => s.pass < s.has).length
  return (
    <article className="doc compare" data-testid="compare">
      <p className="crumb">Compare</p>
      <h1>How react-tils compares</h1>
      <p className="lead">
        The same {tasks.length} everyday tasks in seven React hook libraries, rendered on a real
        server, hydrated in a browser, checked for leaked listeners, and measured. Everything on
        this page is generated by a script you can run yourself.
      </p>
      <ul className="takeaways">
        <li>
          <strong>
            react-tils passes every check on all {ours.has} of {tasks.length} tasks.
          </strong>{' '}
          {othersFailing} of the {others.length} other libraries throw on the server or cause a
          hydration mismatch on at least one, with default settings.
        </li>
        <li>
          <strong>
            Smallest hook on {ours.smallest} of {tasks.length} tasks.
          </strong>{' '}
          @uidotdev/usehooks is often a few bytes smaller, but its hooks for browser state are
          client-only: they throw during server rendering.
        </li>
        <li>
          Only the hooks you import ship to your users. The whole-library sizes are listed at the
          end for reference.
        </li>
      </ul>

      <h2 id="server-rendering">Server rendering</h2>
      <p>
        Each hook is rendered with <code>renderToString</code> in plain Node, then the HTML is
        hydrated in a desktop-sized browser environment, then mounted and unmounted under StrictMode
        to find listeners left behind. Hover a mark for the error.
      </p>
      <div className="support-table-wrap">
        <table className="support-table compare-table" data-testid="compare-checks">
          <thead>
            <tr>
              <th>Task</th>
              {libraries.map(({ id }) => (
                <th key={id} className={id === 'react-tils' ? 'ours' : undefined}>
                  {NAMES[id]}
                </th>
              ))}
            </tr>
          </thead>
          <tbody>
            {tasks.map((task) => (
              <tr key={task.id}>
                <th scope="row">{task.task}</th>
                {libraries.map(({ id }) => {
                  const cell = task.cells[id]
                  if (!cell)
                    return (
                      <td key={id} className="none" aria-label={`${NAMES[id]}: no equivalent hook`}>
                        —
                      </td>
                    )
                  const { mark, label, kind } = verdict(cell)
                  return (
                    <td
                      key={id}
                      className={`${kind}${id === 'react-tils' ? ' ours' : ''}`}
                      title={cell.detail ? `${label}: ${cell.detail}` : label}
                      aria-label={`${NAMES[id]} ${cell.hook}: ${label}`}
                    >
                      <span className="mark">{mark}</span>
                      <code>{cell.hook}</code>
                    </td>
                  )
                })}
              </tr>
            ))}
            <tr className="total">
              <th scope="row">Passes every check</th>
              {summary.map((s) => (
                <td key={s.id} className={s.id === 'react-tils' ? 'ours' : undefined}>
                  {s.pass} / {s.has}
                </td>
              ))}
            </tr>
          </tbody>
        </table>
      </div>
      <ul className="legend">
        <li>
          <span className="mark good">✓</span> Renders on the server, hydrates without a mismatch,
          and leaves no listeners behind.
        </li>
        <li>
          <span className="mark warn">!</span> Hydration mismatch: the browser's first render
          differs from the server HTML, so React throws the server HTML away and re-renders.
        </li>
        <li>
          <span className="mark bad">✕</span> Throws during server rendering, so the page fails
          unless you avoid rendering it on the server.
        </li>
        <li>— No equivalent hook.</li>
      </ul>
      <p className="support-source">
        With each hook's default settings, as most code calls it. Some mismatches can be avoided
        with an option: <code>initializeWithValue: false</code> in usehooks-ts, or a default state
        in react-use's <code>useMedia</code> and @reactuses/core's <code>useMediaQuery</code>.
      </p>

      <h2 id="size">Size per hook</h2>
      <p>
        Bytes after minifying and compressing with brotli, React excluded: what a bundler adds to
        your app for that one hook. The smallest in each row is highlighted.
      </p>
      <div className="support-table-wrap">
        <table className="support-table compare-table" data-testid="compare-sizes">
          <thead>
            <tr>
              <th>Task</th>
              {libraries.map(({ id }) => (
                <th key={id} className={id === 'react-tils' ? 'ours' : undefined}>
                  {NAMES[id]}
                </th>
              ))}
            </tr>
          </thead>
          <tbody>
            {tasks.map((task) => {
              const sizes = Object.values(task.cells)
                .filter(Boolean)
                .map((c) => c!.size)
              const min = Math.min(...sizes)
              return (
                <tr key={task.id}>
                  <th scope="row">{task.task}</th>
                  {libraries.map(({ id }) => {
                    const cell = task.cells[id]
                    const note = task.notes[id]
                    return (
                      <td
                        key={id}
                        className={[
                          cell?.size === min && sizes.length > 1 ? 'best' : '',
                          id === 'react-tils' ? 'ours' : '',
                          cell ? '' : 'none',
                        ]
                          .filter(Boolean)
                          .join(' ')}
                        title={note}
                      >
                        {cell ? `${cell.size} B` : '—'}
                        {note && <sup>*</sup>}
                      </td>
                    )
                  })}
                </tr>
              )
            })}
            <tr className="total">
              <th scope="row">Whole library</th>
              {libraries.map(({ id, size }) => (
                <td key={id} className={id === 'react-tils' ? 'ours' : undefined}>
                  {kb(size)}
                </td>
              ))}
            </tr>
          </tbody>
        </table>
      </div>
      <ul className="legend">
        {tasks.flatMap((task) =>
          Object.entries(task.notes).map(([id, note]) => (
            <li key={`${task.id}-${id}`}>
              <sup>*</sup> {task.task}, {NAMES[id]}: {note}
            </li>
          )),
        )}
        <li>
          Whole-library sizes cover different numbers of hooks; with tree shaking, only the hooks
          you import count.
        </li>
      </ul>

      <h2 id="method">How this was measured</h2>
      <ul>
        <li>
          Versions:{' '}
          {libraries.map(({ id, version }, i) => (
            <span key={id}>
              {i > 0 && ', '}
              {NAMES[id]} {version}
            </span>
          ))}
          . Measured on {data.measured}.
        </li>
        <li>
          Server: <code>renderToString</code> in a Node environment with no DOM at all, as on a real
          server.
        </li>
        <li>
          Hydration: the server HTML is hydrated with <code>hydrateRoot</code> in happy-dom with a
          1024×768 window, online, and an empty localStorage. A mismatch is any recoverable
          hydration error React reports.
        </li>
        <li>
          Leaks: the hook is mounted and unmounted under StrictMode; any event listener added and
          not removed fails it. These are the same checks react-tils runs on its own hooks.
        </li>
        <li>
          Size: each hook imported on its own and bundled with size-limit, React excluded, so every
          library is measured the same way.
        </li>
        <li>
          Not measured here: whether a hook shows the right value on its first frame after
          client-side navigation, and React Compiler support.
        </li>
      </ul>
      <p>
        The script and every hook call are in{' '}
        <a href={`${REPO}/tree/main/compare`}>
          <code>compare/</code>
        </a>
        . Run it with <code>pnpm compare</code>. Spotted an unfair call? Open an issue.
      </p>
    </article>
  )
}
